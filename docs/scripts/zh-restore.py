def main():
    changed = 0
    skipped = 0
    for key, new in EDITS.items():
        rel, _, where = key.partition("::")
        p = ROOT / rel
        if not p.exists():
            print(f"MISSING {rel}")
            continue
        raw = p.read_bytes()
        had_bom = raw.startswith(b"\xef\xbb\xbf")
        text = raw.decode("utf-8-sig")
        try:
            d = json.loads(text)
        except Exception as exc:
            print(f"SKIP {rel}: {exc}")
            continue
        m = __import__("re").match(r"^(\w+)(?:\[(\d+)\])?$", where)
        field, idx = m.group(1), m.group(2)
        v = d.get(field)
        old = v[int(idx)] if (isinstance(v, list) and idx) else v
        if not isinstance(old, str):
            print(f"  {rel} {where}: not a string")
            skipped += 1
            continue
        if old == new:
            continue
        old_item = json.dumps(old, ensure_ascii=False)
        new_item = json.dumps(new, ensure_ascii=False)
        if old_item not in text:
            print(f"  {rel} {where}: current text differs, skipped")
            skipped += 1
            continue
        out = text.replace(old_item, new_item, 1)
        try:
            json.loads(out)
        except Exception as exc:
            print(f"SKIP {rel}: invalid JSON ({exc})")
            skipped += 1
            continue
        if not DRY:
            blob = out.encode("utf-8")
            if had_bom:
                blob = b"\xef\xbb\xbf" + blob
            p.write_bytes(blob)
        changed += 1
        print(f"  {rel} {where}")
    print(f"\n{'would change' if DRY else 'changed'} {changed}, skipped {skipped}")


if __name__ == "__main__":
    main()
